export function calculationSteps(calc, answer) {
  return [
    `Identify the inputs: ${calc.fields.map((f) => `${f.key} = ${formatNumber(answer.values[f.key])} ${f.unit}`).join('; ')}.`,
    scaling[calc.id] || `Keep the stated units consistent. Apply ${calc.formula}.`,
    `Substitute: ${expressions[calc.id](answer.values)}.`,
    `Evaluate: ${formatNumber(answer.result)} ${calc.unit}.`,
  ];
}
