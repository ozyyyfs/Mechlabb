  'flow-rate': (v) => `${v.A} × ${v.v}`,
  'pipe-velocity': (v) => `4 × ${v.Q} ÷ (π × ${v.D}²)`,
  'head-loss': (v) => `${v.f} × (${v.L} ÷ ${v.D}) × ${v.v}² ÷ (2 × 9.81)`,
  'hydraulic-power': (v) => `${v.p} × ${v.Q} ÷ 1000`,
  'pump-power': (v) => `${v.rho} × 9.81 × ${v.Q} × ${v.H} ÷ (${v.eta} ÷ 100) ÷ 1000`,
  'cutting-speed': (v) => `π × ${v.D} × ${v.n} ÷ 1000`,
  rpm: (v) => `1000 × ${v.Vc} ÷ (π × ${v.D})`,
  'feed-rate': (v) => `${v.fz} × ${v.z} × ${v.n}`,
  'machining-time': (v) => `${v.L} ÷ ${v.vf}`,
  mrr: (v) => `${v.ap} × ${v.ae} × ${v.vf}`,
  'second-moment-rect': (v) => `${v.b} × ${v.h}³ ÷ 12`,
  'bending-stress': (v) => `${v.M} × 1000 × ${v.c} ÷ ${v.I}`,
  'beam-ss-deflection': (v) => `${v.F} × ${v.L}³ ÷ (48 × ${v.E} × ${v.I})`,
  'cantilever-deflection': (v) => `${v.F} × ${v.L}³ ÷ (3 × ${v.E} × ${v.I})`,
  'euler-buckling': (v) => `π² × ${v.E} × ${v.I} ÷ (${v.K} × ${v.L})²`,
  'torsional-shear': (v) => `16 × ${v.T} × 1000 ÷ (π × ${v.d}³)`,
  'hoop-stress': (v) => `${v.p} × ${v.d} ÷ (2 × ${v.t})`,
  'flywheel-energy': (v) => `0.5 × ${v.I} × (2π × ${v.n} ÷ 60)²`,
  'belt-length': (v) => `2 × ${v.C} + π × (${v.D} + ${v.d}) ÷ 2 + (${v.D} − ${v.d})² ÷ (4 × ${v.C})`,
  conduction: (v) => `${v.k} × ${v.A} × ${v.dT} ÷ ${v.L}`,
  convection: (v) => `${v.h} × ${v.A} × ${v.dT}`,
  radiation: (v) => `${v.eps} × 5.670374419×10⁻⁸ × ${v.A} × (${v.Th}⁴ − ${v.Tc}⁴)`,
  lmtd: (v) => `(${v.a} − ${v.b}) ÷ ln(${v.a} ÷ ${v.b})`,
